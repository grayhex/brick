static const glyph_t *find_glyph(char c)
{
    if (c >= 'a' && c <= 'z') {
        c = (char)(c - 'a' + 'A');
    }
    for (size_t i = 0; i < sizeof GLYPHS / sizeof GLYPHS[0]; i++) {
        if (GLYPHS[i].c == c) {
            return &GLYPHS[i];
        }
    }
    return NULL;
}

bool bk_font_glyph(char c, uint8_t rows[BK_GLYPH_H])
{
    const glyph_t *g = find_glyph(c);
    if (g == NULL) {
        memset(rows, 0, BK_GLYPH_H);
        return false;
    }
    for (int r = 0; r < BK_GLYPH_H; r++) {
        uint8_t v = 0;
        for (int x = 0; x < BK_GLYPH_W; x++) {
            v = (uint8_t)((v << 1) | (g->rows[r][x] == '#' ? 1u : 0u));
        }
        rows[r] = v;
    }
    return true;
}

int bk_text_width(const char *s, int scale)
{
    int n = (int)strlen(s);
    return n == 0 ? 0 : n * bk_text_pitch(scale) - scale;
}

int bk_text_height(int scale)
{
    return BK_GLYPH_H * scale;
}

void bk_text_draw(bk_frame_t *f, int x, int y, int scale, const char *s)
{
    for (; *s != '\0'; s++, x += bk_text_pitch(scale)) {
        uint8_t rows[BK_GLYPH_H];
        if (!bk_font_glyph(*s, rows)) {
            continue;
        }
        for (int r = 0; r < BK_GLYPH_H; r++) {
            for (int c = 0; c < BK_GLYPH_W; c++) {
                if (rows[r] & (1u << (BK_GLYPH_W - 1 - c))) {
                    bk_frame_fill_rect(f, x + c * scale, y + r * scale, scale, scale, true);
                }
            }
        }
    }
}

