const char *const *bk_big_glyph(char c)
{
    if (c >= '0' && c <= '9') {
        return BIG_DIGITS[c - '0'];
    }
    if (c >= 'a' && c <= 'z') {
        c = (char)(c - 'a' + 'A');
    }
    if (c >= 'A' && c <= 'Z') {
        return BIG_LETTERS[c - 'A'];
    }
    return NULL;
}

const char *const *bk_small_digit(int d)
{
    return (d >= 0 && d <= 9) ? SMALL_DIGITS[d] : NULL;
}
